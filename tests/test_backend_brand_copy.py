def test_notification_and_model_endpoint_copy_has_no_legacy_product_name():
    expected = {
        "routes/auth_routes.py": (
            "OM Automate connectivity test",
            "Connectivity test from OM Automate",
        ),
        "routes/email_pollers.py": ("Open in OM Automate",),
        "routes/model_routes.py": ("That is OM Automate, not a model server",),
        "services/hwfit/hardware.py": ("inside the OM Automate container",),
    }
    forbidden = (
        "Odysseus connectivity test",
        "Connectivity test from Odysseus",
        "Open in Odysseus",
        "That is Odysseus, not a model server",
        "inside the Odysseus container",
    )

    for relative_path, required_strings in expected.items():
        source = (ROOT / relative_path).read_text(encoding="utf-8")
        assert all(value in source for value in required_strings)
        assert all(value not in source for value in forbidden)


