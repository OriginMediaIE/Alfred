ROOT = Path(__file__).resolve().parents[1]
GREEK_PERSONA_TERMS = ("king of ithaca", "homer", "odyssey", "telemachus", "penelope")


def test_default_model_prompts_use_central_om_persona_without_greek_roleplay():
    configured = get_brand_config().copy_text.default_persona
    prompts = [
        _minimal_odysseus_doc_messages([], None, stream_create=True)[0]["content"],
        _minimal_odysseus_doc_messages([], None, stream_create=False)[0]["content"],
        _minimal_odysseus_notes_messages([])[0]["content"],
        _minimal_odysseus_general_messages([])[0]["content"],
        PERSONAS["odysseus"],  # persisted compatibility ID
    ]

    for prompt in prompts:
        assert configured in prompt
        lowered = prompt.lower()
        assert "you are odysseus" not in lowered
        assert all(term not in lowered for term in GREEK_PERSONA_TERMS)


