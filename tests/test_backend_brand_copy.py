def test_totp_issuer_and_oauth_page_use_om_brand(tmp_path):
    manager = AuthManager(str(tmp_path / "auth.json"))
    uri = manager.totp_get_provisioning_uri("alice", "JBSWY3DPEHPK3PXP")
    issuer = parse_qs(urlparse(uri).query)["issuer"]

    assert issuer == ["OM Automate"]
    page = _oauth_authorize_page(
        "https://accounts.example/authorize",
        "server-1",
        "localhost:7000",
    )
    assert "Authorize — OM Automate" in page
    assert "Authorize — Odysseus" not in page


